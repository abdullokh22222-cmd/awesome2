const scrollProgress = document.querySelector(".scroll-progress");
const heroVideo = document.querySelector(".hero-video");
const videoToggle = document.querySelector(".video-toggle");
const contactForm = document.querySelector(".contact-form");
const formStatus = document.querySelector(".form-status");
const languageButtons = document.querySelectorAll("[data-lang]");
const translatedNodes = document.querySelectorAll("[data-i18n]");
const placeholderNodes = document.querySelectorAll("[data-i18n-placeholder]");
const siteHeader = document.querySelector(".site-header");
const menuToggle = document.querySelector(".menu-toggle");
const navLinks = document.querySelectorAll(".main-nav a");
const GOOGLE_SCRIPT_URL = "https://script.google.com/macros/s/AKfycbwAuK7CweGDJmnj1w182FAfH5hSPo31q0XnkU2WcqqN3vz_8Dzswlyi4DSqTxrmXSZT7w/exec";
let currentLanguage = localStorage.getItem("hype-production-lang") || "en";

function updateVideoToggleLabel() {
  if (!videoToggle || !heroVideo) {
    return;
  }

  const dictionary = translations[currentLanguage] || translations.en;
  videoToggle.textContent = heroVideo.paused ? dictionary.videoPlay : dictionary.videoPause;
}

function setLanguage(lang) {
  const dictionary = translations[lang] || translations.en;
  currentLanguage = lang;

  translatedNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  placeholderNodes.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dictionary[key]) {
      node.placeholder = dictionary[key];
    }
  });

  languageButtons.forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });

  document.documentElement.lang = lang;
  localStorage.setItem("hype-production-lang", lang);
  updateVideoToggleLabel();
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

menuToggle?.addEventListener("click", () => {
  const isOpen = siteHeader?.classList.toggle("menu-open");
  menuToggle.setAttribute("aria-expanded", String(Boolean(isOpen)));
});

navLinks.forEach((link) => {
  link.addEventListener("click", () => {
    siteHeader?.classList.remove("menu-open");
    menuToggle?.setAttribute("aria-expanded", "false");
  });
});

videoToggle?.addEventListener("click", () => {
  if (!heroVideo) {
    return;
  }

  if (heroVideo.paused) {
    heroVideo.play();
  } else {
    heroVideo.pause();
  }

  updateVideoToggleLabel();
});

window.addEventListener("scroll", () => {
  if (!scrollProgress) {
    return;
  }

  const scrollable = document.documentElement.scrollHeight - window.innerHeight;
  const progress = scrollable > 0 ? (window.scrollY / scrollable) * 100 : 0;
  scrollProgress.style.width = `${progress}%`;
});

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
      }
    });
  },
  { threshold: 0.12 },
);

document.querySelectorAll(".reveal").forEach((node) => revealObserver.observe(node));

contactForm?.addEventListener("submit", async (event) => {
  event.preventDefault();
  const dictionary = translations[currentLanguage] || translations.en;

  if (formStatus) {
    formStatus.textContent = dictionary.formSending;
  }

  if (!GOOGLE_SCRIPT_URL) {
    if (formStatus) {
      formStatus.textContent = dictionary.formNoEndpoint;
    }
    return;
  }

  const formData = new FormData(contactForm);
  const payload = {
    name: formData.get("name"),
    phone: formData.get("phone"),
    project: formData.get("project"),
    language: currentLanguage,
    page: window.location.href,
  };

  try {
    await fetch(GOOGLE_SCRIPT_URL, {
      method: "POST",
      mode: "no-cors",
      headers: {
        "Content-Type": "text/plain;charset=utf-8",
      },
      body: JSON.stringify(payload),
    });

    contactForm.reset();
    if (formStatus) {
      formStatus.textContent = dictionary.formSuccess;
    }
  } catch (error) {
    if (formStatus) {
      formStatus.textContent = dictionary.formError;
    }
  }
});

heroVideo?.addEventListener("play", updateVideoToggleLabel);
heroVideo?.addEventListener("pause", updateVideoToggleLabel);
setLanguage(currentLanguage);
